use std::fs;
use std::path::{Path, PathBuf};

fn collect_svg_files(directory: &Path, files: &mut Vec<PathBuf>) {
    let mut entries: Vec<_> = fs::read_dir(directory)
        .unwrap_or_else(|error| panic!("failed to read {}: {error}", directory.display()))
        .map(|entry| entry.expect("failed to read asset directory entry").path())
        .collect();
    entries.sort();

    for path in entries {
        if path.is_dir() {
            collect_svg_files(&path, files);
        } else if path.extension().is_some_and(|extension| extension == "svg") {
            files.push(path);
        }
    }
}

/// Embed the app icon (resource id 1, which GPUI loads for the window/taskbar
/// icon), the Windows application manifest, and version metadata into the .exe.
#[cfg(windows)]
fn embed_windows_resources(manifest_dir: &Path) {
    let icon = manifest_dir.join("assets/appicon/app.ico");
    println!("cargo:rerun-if-changed={}", icon.display());

    // Icon (resource id 1, which GPUI's LoadImageW picks up) + version info.
    // The application manifest is embedded by GPUI itself (its `windows-manifest`
    // feature embeds resources/windows/gpui.manifest.xml as RT_MANIFEST id 1);
    // embedding a second manifest resource here would collide (CVT1100).
    // rc.exe accepts forward slashes, which sidesteps backslash escaping.
    let icon_rc = icon.to_string_lossy().replace('\\', "/");
    let rc = format!(
        r#"1 ICON "{icon_rc}"

1 VERSIONINFO
FILEVERSION 0,1,0,0
PRODUCTVERSION 0,1,0,0
FILEOS 0x40004L
FILETYPE 0x1L
BEGIN
  BLOCK "StringFileInfo"
  BEGIN
    BLOCK "040904b0"
    BEGIN
      VALUE "CompanyName", "Futureboard Studio"
      VALUE "FileDescription", "Trash Browser"
      VALUE "FileVersion", "0.1.0.0"
      VALUE "InternalName", "trashbrowser-gpui"
      VALUE "LegalCopyright", "Copyright (C) Futureboard Studio"
      VALUE "OriginalFilename", "trashbrowser-gpui.exe"
      VALUE "ProductName", "Trash Browser"
      VALUE "ProductVersion", "0.1.0.0"
    END
  END
  BLOCK "VarFileInfo"
  BEGIN
    VALUE "Translation", 0x409, 1200
  END
END
"#
    );

    let out_dir = PathBuf::from(std::env::var_os("OUT_DIR").unwrap());
    let rc_path = out_dir.join("trashbrowser.rc");
    fs::write(&rc_path, rc)
        .unwrap_or_else(|error| panic!("failed to write {}: {error}", rc_path.display()));

    embed_resource::compile(&rc_path, embed_resource::NONE)
        .manifest_optional()
        .expect("failed to embed Windows resources");
}

fn main() {
    const ASSET_ROOT: &str = "assets/tabler_icons";
    println!("cargo:rerun-if-changed={ASSET_ROOT}");
    println!("cargo:rerun-if-changed=shell/dist/index.html");

    let manifest_dir = PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").unwrap());

    #[cfg(windows)]
    embed_windows_resources(&manifest_dir);
    let mut files = Vec::new();
    collect_svg_files(&manifest_dir.join(ASSET_ROOT), &mut files);

    let mut generated = String::from(
        "// Generated by build.rs. Do not edit.\n\
         pub static PATHS: &[&str] = &[\n",
    );
    for file in &files {
        let relative = file
            .strip_prefix(&manifest_dir)
            .expect("asset must be inside the crate")
            .to_string_lossy()
            .replace('\\', "/");
        generated.push_str(&format!("    {relative:?},\n"));
    }
    generated.push_str("];\n\npub fn get(path: &str) -> Option<&'static [u8]> {\n    match path {\n");
    for file in &files {
        let relative = file
            .strip_prefix(&manifest_dir)
            .expect("asset must be inside the crate")
            .to_string_lossy()
            .replace('\\', "/");
        let absolute = file.to_string_lossy().replace('\\', "/");
        generated.push_str(&format!(
            "        {relative:?} => Some(include_bytes!(r#{absolute:?}#)),\n"
        ));
    }
    generated.push_str("        _ => None,\n    }\n}\n");

    let output = PathBuf::from(std::env::var_os("OUT_DIR").unwrap()).join("tabler_assets.rs");
    fs::write(&output, generated)
        .unwrap_or_else(|error| panic!("failed to write {}: {error}", output.display()));
}
